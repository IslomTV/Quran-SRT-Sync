# Fast lookup dict by surah number
SURAHS_BY_NUMBER = {s[0]: {
    'number': s[0],
    'arabic_name': s[1],
    'english_name': s[2],
    'ayah_count': s[3],
    'opening': s[4]
} for s in SURAHS_DATA}


def detect_surah_from_text(text: str) -> dict | None:
    """
    Attempts to identify the Surah being recited by checking keywords in the subtitle text.
    Returns Surah metadata dict or None if ambiguous/mid-surah.
    """
    if not text:
        return None

    norm_input = normalize_arabic(text)
    if not norm_input:
        return None

    # Check each surah opening phrase
    best_match = None
    best_score = 0

    for s_num, ar_name, en_name, ayahs, opening in SURAHS_DATA:
        norm_opening = normalize_arabic(opening)
        # Check if the opening occurs in the text
        if norm_opening in norm_input:
            score = len(norm_opening)
            if score > best_score:
                best_score = score
                best_match = SURAHS_BY_NUMBER[s_num]

    return best_match

